export function getSeoLandingPage(slug: string) {
  return seoLandingPages.find((page) => page.slug === slug);
}

export function getSeoLandingPath(slug: string) {
  return `/${slug}`;
}

export function getRelatedSeoLandingPages(page: SeoLandingPage) {
  const seenSlugs = new Set<string>();

  return page.relatedSlugs.flatMap((slug) => {
    if (slug === page.slug || seenSlugs.has(slug)) {
      return [];
    }

    seenSlugs.add(slug);
    const relatedPage = getSeoLandingPage(slug);

    return relatedPage ? [relatedPage] : [];
  });
}
